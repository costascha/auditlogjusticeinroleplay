create sequence if not exists public.ticket_number_seq
    as bigint
    minvalue 1000000000000000
    maxvalue 9999999999999999
    start with 1000000000000000
    increment by 1
    no cycle;

do $$
begin
    if to_regclass('public.users') is null and to_regclass('public.profiles') is not null then
        alter table public.profiles rename to users;
    end if;
end;
$$;

create table if not exists public.users (
    id uuid primary key references auth.users (id) on delete cascade,
    username text,
    is_admin boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.users
    add column if not exists username text;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'users_username_format'
          and conrelid = 'public.users'::regclass
    ) then
        alter table public.users
            add constraint users_username_format
            check (username is null or username ~ '^[a-z0-9._-]{3,32}$');
    end if;
end;
$$;

create unique index if not exists users_username_lower_unique_idx
    on public.users (lower(username))
    where username is not null;

create table if not exists public.tickets (
    ticket_number text primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    subject text not null check (char_length(btrim(subject)) between 1 and 120),
    description text not null check (char_length(btrim(description)) between 1 and 5000),
    status text not null default 'open'
        check (status in ('open', 'in_progress', 'resolved', 'closed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ticket_number_format check (ticket_number ~ '^1-[0-9]{16}$')
);

create table if not exists public.audit_logs (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    action text not null check (action in ('user_registered')),
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_idx
    on public.audit_logs (created_at desc);

create table if not exists public.notification_queue (
    id bigint generated by default as identity primary key,
    audit_log_id bigint not null unique references public.audit_logs (id) on delete cascade,
    user_id uuid not null references auth.users (id) on delete cascade,
    title text not null,
    body text not null,
    status text not null default 'pending'
        check (status in ('pending', 'processing', 'sent', 'failed')),
    attempts integer not null default 0 check (attempts >= 0),
    available_at timestamptz not null default now(),
    sent_at timestamptz,
    last_error text,
    created_at timestamptz not null default now()
);

create index if not exists notification_queue_pending_idx
    on public.notification_queue (available_at, id)
    where status = 'pending';

create index if not exists tickets_user_created_idx
    on public.tickets (user_id, created_at desc);

