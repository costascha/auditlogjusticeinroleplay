create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.users
        where id = (select auth.uid())
          and is_admin
    );
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    registered_username text;
    audit_id bigint;
begin
    registered_username := nullif(lower(btrim(new.raw_user_meta_data ->> 'username')), '');

    insert into public.users (id, username)
    values (
        new.id,
        registered_username
    )
    on conflict (id) do nothing;

    insert into public.audit_logs (user_id, action, details)
    values (
        new.id,
        'user_registered',
        jsonb_build_object(
            'username', registered_username,
            'auth_provider', coalesce(new.raw_app_meta_data ->> 'provider', 'email')
        )
    )
    returning id into audit_id;

    insert into public.notification_queue (
        audit_log_id,
        user_id,
        title,
        body
    )
    values (
        audit_id,
        new.id,
        'Νέα εγγραφή χρήστη',
        case
            when registered_username is null then 'Ένας νέος χρήστης ολοκλήρωσε την εγγραφή.'
            else 'Ο χρήστης ' || registered_username || ' ολοκλήρωσε την εγγραφή.'
        end
    );

    return new;
end;
$$;

revoke all on function public.create_profile_for_new_user() from public, anon, authenticated;
drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup
    after insert on auth.users
    for each row execute function public.create_profile_for_new_user();

insert into public.users (id)
select id from auth.users
on conflict (id) do nothing;

create or replace function public.ensure_current_user_profile()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_user_id uuid := (select auth.uid());
    current_username text;
begin
    if current_user_id is null then
        raise exception 'An authenticated user is required';
    end if;

    select nullif(lower(btrim(raw_user_meta_data ->> 'username')), '')
    into current_username
    from auth.users
    where id = current_user_id;

    if current_username is not null
       and current_username !~ '^[a-z0-9._-]{3,32}$'
    then
        current_username := null;
    end if;

    insert into public.users as u (id, username)
    values (current_user_id, current_username)
    on conflict (id) do update
    set username = coalesce(u.username, excluded.username);
end;
$$;

revoke all on function public.ensure_current_user_profile() from public, anon;
grant execute on function public.ensure_current_user_profile() to authenticated;

create or replace function public.prepare_new_ticket()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if auth.uid() is null then
        raise exception 'An authenticated user is required to create a ticket';
    end if;

    new.ticket_number := '1-' || lpad(nextval('public.ticket_number_seq')::text, 16, '0');
    new.user_id := auth.uid();
    new.status := 'open';
    new.created_at := now();
    new.updated_at := new.created_at;
    return new;
end;
$$;

revoke all on function public.prepare_new_ticket() from public, anon, authenticated;
drop trigger if exists prepare_ticket_before_insert on public.tickets;
create trigger prepare_ticket_before_insert
    before insert on public.tickets
    for each row execute function public.prepare_new_ticket();

